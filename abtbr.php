 <p><br><br>Wolaita sodo school bureau is found in Wolaita Zone Sodo City Administration. It was established in the year 1930. Wolaita Sodo City, the administrative capital of wolaita  and serve as administrative, commercial and transport centre of the Zone. The City is located at 270 km distance from Addis Ababa via Hossana and 295 km via Shashemene. From regional capital Hawassa located at a distance of 170 km and found at south west of Addis Ababa and Hawassa respectively. The Italian period saw the opening of two schools, i.e., Cappuccino Mission Schools for civilian and Consulate Military Training school, where medium of instruction was in Italian language. It gave service only for the Italians.  After liberation, Modern education was started with the opening of Ligaba Beyene Primary School in 1945. This school was named after Ligaba Beyene, because it was constructed in Ligaba Beyene Ghibi (residence). Ato Bogale Walelu and Ato Wana Wegesho played a vital role for the initiation of the school. The School was upgraded to junior secondary school level (up to grade 8) in 1951. Following Ligaba elementary school, Otona (1950), Hohte Berhan (1965) and Wolaita Sodo Giorgis (1966) elementary schools were established.<br> 
